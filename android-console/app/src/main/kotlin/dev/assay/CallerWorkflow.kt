package dev.assay

/**
 * The thin caller workflow the console proposes to a target repository. It must stay equivalent to
 * `assay init-actions` in the engine (InitActions.kt); the dispatch inputs below are the ones the
 * Runs screen sends.
 */
object CallerWorkflow {
    const val PATH = ".github/workflows/assay.yml"
    const val FILE = "assay.yml"

    fun render(assayRef: String): String {
        require(assayRef.matches(Regex("[A-Za-z0-9._/-]{1,100}")) && !assayRef.contains("..")) { "Invalid ref" }
        return TEMPLATE.replace("@@REF@@", assayRef).replace("§", "$")
    }

    // `§` stands in for `$` so Kotlin does not treat `${{ ... }}` as a string template.
    private val TEMPLATE = """
# Generated by the Assay console. Runs Assay's hosted audit; see docs/RUNNER-ACTIONS.md in mbaliga/assay.
name: Assay audit
on:
  workflow_dispatch:
    inputs:
      output_branch:
        description: Branch that receives the .assay/ output
        default: assay/output
      scanners:
        description: Comma-separated subset of gitleaks,semgrep,osv,mobsf
        default: gitleaks,semgrep,osv
      build_apk:
        description: Build the debug APK first (needed for mobsf)
        type: boolean
        default: false
permissions:
  contents: read
jobs:
  audit:
    permissions:
      contents: write
    uses: mbaliga/assay/.github/workflows/assay-audit.yml@@@REF@@
    with:
      assay_ref: @@REF@@
      output_branch: §{{ inputs.output_branch }}
      scanners: §{{ inputs.scanners }}
      build_apk: §{{ inputs.build_apk }}
""".trimStart()
}
