package dev.assay

import java.nio.file.Files
import java.nio.file.LinkOption
import java.nio.file.Path

/**
 * `assay init-actions --repo PATH [--assay-ref REF] [--force]` writes the thin caller workflow
 * `.github/workflows/assay.yml` that runs Assay's reusable hosted audit
 * (`.github/workflows/assay-audit.yml`, docs/RUNNER-ACTIONS.md) from `workflow_dispatch`.
 */
object InitActionsCli {
    private const val COMMAND = "init-actions"
    const val CALLER_PATH = ".github/workflows/assay.yml"

    fun handles(command: String?): Boolean = command == COMMAND

    fun run(args: Array<String>) {
        require(args.firstOrNull() == COMMAND) { "unsupported command" }
        val rest = args.drop(1)
        var repo: String? = null
        var ref = "main"
        var force = false
        var index = 0
        while (index < rest.size) {
            when (rest[index]) {
                "--repo" -> { repo = rest.getOrNull(++index) ?: error("missing value for --repo") }
                "--assay-ref" -> { ref = rest.getOrNull(++index) ?: error("missing value for --assay-ref") }
                "--force" -> force = true
                else -> error("unexpected argument '${rest[index]}'")
            }
            index++
        }
        val written = write(Path.of(repo ?: error("missing --repo")), ref, force)
        println("wrote $written")
        if (ref == "main") {
            println("note: pin --assay-ref to a commit SHA for production use")
        }
    }

    fun write(repo: Path, assayRef: String, force: Boolean = false): Path {
        require(assayRef.matches(Regex("[A-Za-z0-9._/-]{1,100}")) && !assayRef.contains("..")) {
            "invalid --assay-ref"
        }
        val root = repo.toAbsolutePath().normalize()
        require(Files.isDirectory(root, LinkOption.NOFOLLOW_LINKS) && !Files.isSymbolicLink(root)) {
            "--repo must be a real directory"
        }
        val target = root.resolve(CALLER_PATH)
        var cursor = root
        for (segment in listOf(".github", "workflows")) {
            cursor = cursor.resolve(segment)
            require(!Files.isSymbolicLink(cursor)) { "$segment must not be a symlink" }
        }
        require(force || !Files.exists(target, LinkOption.NOFOLLOW_LINKS)) {
            "$CALLER_PATH already exists; pass --force to replace it"
        }
        require(!Files.isSymbolicLink(target)) { "$CALLER_PATH must not be a symlink" }
        Files.createDirectories(target.parent)
        Files.writeString(target, render(assayRef))
        return target
    }

    fun render(assayRef: String): String = TEMPLATE
        .replace("@@REF@@", assayRef)
        .replace("§", "$")

    // `§` stands in for `$` so Kotlin does not treat `${{ ... }}` as a string template.
    private val TEMPLATE = """
# Generated by `assay init-actions`. Runs Assay's hosted audit; see docs/RUNNER-ACTIONS.md in mbaliga/assay.
name: Assay audit
on:
  workflow_dispatch:
    inputs:
      output_branch:
        description: Branch that receives the .assay/ output
        default: assay/output
      scanners:
        description: Comma-separated subset of gitleaks,semgrep,osv,mobsf
        default: gitleaks,semgrep,osv
      build_apk:
        description: Build the debug APK first (needed for mobsf)
        type: boolean
        default: false
permissions:
  contents: read
jobs:
  audit:
    permissions:
      contents: write
    uses: mbaliga/assay/.github/workflows/assay-audit.yml@@@REF@@
    with:
      assay_ref: @@REF@@
      output_branch: §{{ inputs.output_branch }}
      scanners: §{{ inputs.scanners }}
      build_apk: §{{ inputs.build_apk }}
""".trimStart()
}
